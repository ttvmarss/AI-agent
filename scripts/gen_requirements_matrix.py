#!/usr/bin/env python3
"""Generate docs/specs/REQUIREMENTS_MATRIX.md from the blueprint.

Every requirement ID found in the blueprint gets one row. Milestone mapping is
a proposal (M0 output) driven by the PREFIX_RULES table below; owner approves.
Usage: python3 -I scripts/gen_requirements_matrix.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BP = ROOT / "docs/blueprint/ZALIUS_AI_MASTER_ENGINEERING_BLUEPRINT_v1.3_RELEASE_ARCHITECTURE.md"
OUT = ROOT / "docs/specs/REQUIREMENTS_MATRIX.md"

PREFIXES = ["OWN", "APP", "PROJ", "MEM", "VOICE", "SET", "API", "AGENT", "CODE",
            "EVO", "TB", "DEP", "SEC", "UPD", "BENCH", "XP", "REPRO", "REL", "BIZ"]
# Ranges stated in headings/prose but not enumerated individually in the blueprint.
RANGES = {"PROJ": 7, "MEM": 10, "VOICE": 9, "SET": 20}

text = BP.read_text(encoding="utf-8")
ids = set()
for p in PREFIXES:
    for m in re.finditer(rf"\b{p}-(\d{{3}})\b", text):
        ids.add(f"{p}-{m.group(1)}")
    # expand "XXX-001 to XXX-014" / "XXX-001..014" style ranges
    for m in re.finditer(rf"\b{p}-(\d{{3}})\s*(?:to|\.\.|–|-)\s*(?:{p}-)?(\d{{3}})\b", text):
        for n in range(int(m.group(1)), int(m.group(2)) + 1):
            ids.add(f"{p}-{n:03d}")
for p, n in RANGES.items():
    for i in range(1, n + 1):
        ids.add(f"{p}-{i:03d}")
for m in re.finditer(r"\bCODE-G[0-5]\b|\bW-0[1-7]\b|\bR-01\b|\b(?:DEP|SEC|UPD|BENCH|XP|REPRO)-G1\b", text):
    ids.add(m.group(0))
for n in range(1, 28):
    ids.add(f"TB-{n:03d}")  # TB-001..027 mandated by kickoff

def key(i):
    m = re.match(r"([A-Z]+)-(G?)(\d+)", i)
    return (PREFIXES.index(m.group(1)) if m.group(1) in PREFIXES else 99, m.group(2), int(m.group(3)))

def milestone(i):
    p, rest = i.split("-", 1)
    n = int(re.sub(r"\D", "", rest) or 0)
    if i == "R-01": return "M0"
    if p == "W": return "M8" if n in (1, 2, 5, 6) else "M9"
    if p == "OWN": return "All (verified at M4, M5, M11)"
    if p == "APP": return "M5"
    if p in ("PROJ", "MEM"): return "M6"
    if p == "SET": return "M6 (persistence) / per-feature milestone"
    if p == "VOICE": return "M7"
    if p == "API": return "M9"
    if p == "AGENT": return "M10" if n != 7 and n != 11 else "M10C"
    if p == "CODE":
        if rest == "G0": return "M0"
        if rest == "G1": return "M4C"
        if rest in ("G2", "G3"): return "M10C"
        if rest in ("G4", "G5"): return "M11P"
        return "M10C" if n != 17 else "M11"
    if p == "EVO": return "M11"
    if p == "TB":
        if n <= 5: return "M1 (design M0)"
        if n in (6, 7): return "M3/M4"
        if n == 8: return "M4/M10C"
        if n in (9, 10): return "M5/M6"
        if n == 11: return "M7"
        if n in (12, 13): return "M8-M10"
        if n == 14: return "M5-M11T"
        if n == 15: return "M12W/M12M"
        if n in (16, 17, 18, 19, 20): return "M11T (M1 scaffold)"
        if n in (21, 22, 23, 24): return "M11 (policy in M1)"
        return "M11T/M12R"
    if p == "DEP": return "M5 (001,003,005); M10 (007); M12W/M (002,008); P3 (004)"
    if p == "SEC": return "M1 (design), M5-M9 impl, M12 (007), P3 (010)"
    if p == "UPD": return "M5 (001,004,008); M12W/M12M (rest)"
    if p == "BENCH": return "M2 (001,007); M4 (002,003); M4C/M10C (004); later rest"
    if p == "XP": return "M5 (001,002); M8-M9 (003); M12M (004,009); M12 (rest)"
    if p == "REPRO": return "M1-M4 (001-004,006,008); M12 (005,009); P3 (010)"
    if p == "REL": return "M11T (001,003,004); M12R (005,007); M12S (008,009)"
    if p == "BIZ": return "M13 (deferred; no work before)"
    return "TBD"

def test_ref(i):
    p = i.split("-")[0]
    suite = {"OWN": "tests/model + tests/security", "APP": "tests/browser", "PROJ": "tests/browser+integration",
             "MEM": "tests/integration", "SET": "tests/browser", "VOICE": "tests/voice", "W": "tests/windows",
             "API": "tests/integration", "AGENT": "tests/integration+e2e", "CODE": "model/eval/coding + benchmarks",
             "EVO": "tests/model + testbench", "TB": "testbench self-tests", "DEP": "tests/integration",
             "SEC": "tests/security", "UPD": "tests/upgrade", "BENCH": "benchmarks/", "XP": "tests/windows|macos",
             "REPRO": "tests/repro", "REL": "tests/installer + release gate", "BIZ": "n/a until M13", "R": "docs/research review"}[p]
    return f"T-{i}-HP / T-{i}-FAIL ({suite}) [TBD in spec]"

rows = sorted(ids, key=key)
lines = ["# Requirements Traceability Matrix (M0 proposal)", "",
         f"Generated by `scripts/gen_requirements_matrix.py` from the v1.3 blueprint. **{len(rows)} rows.**",
         "State vocabulary (TB-002): planned / implemented / automated / passing / failing / flaky / blocked / n/a.",
         "**All rows are `planned` except where noted: nothing is implemented or tested.** Test IDs are placeholders "
         "reserved by naming convention; they are not existing tests. Milestone mapping is a proposal for owner approval.",
         "ID ranges PROJ/MEM/VOICE/SET are defined in the blueprint only as ranges; individual rows were expanded and "
         "each needs its `specs/<ID>.md` elaborated in its milestone.", "",
         "| ID | Milestone (proposed) | Acceptance test (reserved ID) | State |", "|---|---|---|---|"]
for i in rows:
    state = "planned (M0 doc deliverable)" if i in ("R-01", "CODE-G0") else "planned"
    lines.append(f"| {i} | {milestone(i)} | {test_ref(i)} | {state} |")
lines += ["", "## Counts by family", ""]
fam = {}
for i in rows:
    fam[i.split("-")[0]] = fam.get(i.split("-")[0], 0) + 1
lines += [f"- {k}: {v}" for k, v in sorted(fam.items())]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT} with {len(rows)} rows")
print(fam)
